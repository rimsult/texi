function pluralRu(n: number, one: string, few: string, many: string): string {
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few;
  return many;
}

/** Definitions are chosen per level (data-pipeline/lexi_pipeline/adapt.py); the UI explains it. */
type LevelBand = "basic" | "mixed" | "precise";
export const definitionBand = (level: Level): LevelBand =>
  level === "A1" || level === "A2" || level === "B1" ? "basic" : level === "B2" ? "mixed" : "precise";

